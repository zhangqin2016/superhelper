export const ENTERPRISE_CONSOLE_DICTIONARIES = Object.freeze({ zh, en, ar });

const LOCALE_TAGS = { zh: "zh-CN", en: "en-US", ar: "ar" };

function normalize(locale) {
  return ["zh", "en", "ar"].includes(locale) ? locale : "zh";
}

/** The whole console dictionary for `locale` (zh when unknown). */
export function enterpriseConsoleText(locale) {
  return ENTERPRISE_CONSOLE_DICTIONARIES[normalize(locale)];
}

/** Fill {name} slots in a template. */
export function fill(template, values = {}) {
  return String(template ?? "").replace(/\{(\w+)\}/g, (_, key) => (values[key] ?? values[key] === 0 ? String(values[key]) : ""));
}

export function formatNumber(value, locale) {
  const n = Number(value || 0);
  return Number.isFinite(n) ? n.toLocaleString(LOCALE_TAGS[normalize(locale)]) : "0";
}

export function formatDate(value, locale) {
  const date = value ? new Date(value) : null;
  if (!date || Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(LOCALE_TAGS[normalize(locale)], { dateStyle: "medium" }).format(date);
}

export function formatDateTime(value, locale) {
  const date = value ? new Date(value) : null;
  if (!date || Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat(LOCALE_TAGS[normalize(locale)], { dateStyle: "medium", timeStyle: "short" }).format(date);
}

/** A budget value as a person reads it: a number, or "unlimited" for null. */
export function formatBudget(value, locale) {
  return value === null || value === undefined ? enterpriseConsoleText(locale).common.unlimited : formatNumber(value, locale);
}

/** A wallet amount with its unit: "12,000 积分" / "12,000 credits". The pool, budgets and caps are credits, not model tokens. */
export function formatCredits(value, locale) {
  return `${formatNumber(value, locale)} ${enterpriseConsoleText(locale).common.units}`;
}

/** A credit budget: "12,000 积分", or "unlimited" for null. */
export function formatCreditBudget(value, locale) {
  return value === null || value === undefined ? enterpriseConsoleText(locale).common.unlimited : formatCredits(value, locale);
}

/**
 * A readable sentence for a failure: the server code's own message when there
 * is one, otherwise a plain "did not complete / could not load" — never the
 * raw code (NETWORK_ERROR, HTTP_502, a Postgres number...).
 */
export function consoleErrorMessage(codeOrError, locale, kind = "action") {
  const raw = typeof codeOrError === "string" ? codeOrError : "";
  const code = ENTERPRISE_MESSAGE_CODES.includes(raw) ? raw : enterpriseErrorCode(codeOrError);
  if (code && ENTERPRISE_MESSAGE_CODES.includes(code)) return enterpriseMessage(code, normalize(locale));
  const text = enterpriseConsoleText(locale).common;
  return kind === "load" ? text.loadFailed : text.failed;
}

/** Who a person is, in the order people recognise them. Never a bare usr_ id. */
export function personLabel(person, fallback = "") {
  if (!person) return fallback;
  const name = person.displayName || person.display_name || "";
  const login = person.loginName || person.login_name || "";
  const phone = person.phone || person.phoneMasked || "";
  return name || login || phone || fallback;
}

/** The secondary line under a person's name (login name / masked phone). */
export function personDetail(person) {
  if (!person) return "";
  const name = person.displayName || person.display_name || "";
  const parts = [person.loginName || person.login_name || "", person.phone || person.phoneMasked || ""].filter(Boolean);
  return (name ? parts : parts.slice(1)).join(" · ");
}

/** The organization's state in one word: active, paused (by its owner) or frozen (by the platform). */
export function organizationState(org) {
  if (!org) return "active";
  if (org.platform_status === "suspended") return "frozen";
  if (org.owner_status === "disabled" || org.status === "disabled") return "paused";
  return "active";
}
