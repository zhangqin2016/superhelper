import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {CollaborationStore}=require('../src/main/collaboration/collaboration-store');
const {LocalCollaborationKeyring}=require('../src/main/collaboration/local-keyring');
const {createTaskCommands}=require('../src/main/collaboration/task-commands');
const {taskView,taskCommand,taskResult}=require('../src/main/collaboration/task-view');
const {createCollaborationIpc}=require('../src/main/ipc-collaboration');
const directory=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'task-git-desktop-'));
const inputGit={version:1,format:'git-bundle-v2',ref:`refs/tasks/${'a'.repeat(64)}/baseline`,commit:'b'.repeat(40),prerequisites:[],sha256:'c'.repeat(64),sizeBytes:500};
const deliveryGit={...inputGit,ref:`refs/tasks/${'a'.repeat(64)}/deliveries/${'d'.repeat(64)}`,commit:'e'.repeat(40),prerequisites:[inputGit.commit]};
const task={id:'task',conversationId:'chat',requesterUserId:'owner',assigneeUserId:'helper',inputSnapshotId:'input',inputGit,title:'Task',objective:'Work',acceptanceCriteria:'Checked',state:'active',revision:2,createdAt:1,updatedAt:2,deliveries:[],currentDeliveryId:null,acceptedDeliveryId:null};
const options={accountId:'helper',dbPath:path.join(directory,'cache.db'),keyring:new LocalCollaborationKeyring({filePath:path.join(directory,'keys'),safeStorage:{isEncryptionAvailable:()=>true,encryptString:value=>Buffer.from(value),decryptString:value=>value.toString()}})};
let store,calls=[],unknown=true;
const client={getTask:async()=>structuredClone(task),submitTask:async input=>{calls.push(input);if(unknown)throw Object.assign(new Error('lost'),{code:'COLLAB_RESPONSE_UNKNOWN'});return {ok:true,result:{taskId:'task',state:'review',revision:3}};}};
const open=()=>{store=new CollaborationStore(options);store.db.run("INSERT OR IGNORE INTO conversations(account_id,id,scope_id,kind,updated_at) VALUES ('helper','chat','personal','direct',0)");return createTaskCommands({store,client,deviceId:'device',assertActive:()=>{}});};
try {
 let tasks=open();
 const internal=await tasks.get({conversationId:'chat',taskId:'task'});
 assert.deepEqual(internal.task.inputGit,inputGit,'main workflow retains validated Git descriptor');
 assert.equal(taskResult('getTask',internal).task.inputGit,undefined,'IPC projection strips Git metadata');
 assert.equal(taskView({...task,inputGit:{...inputGit,repository:'/private'}}),null,'invalid private metadata cannot silently become a ZIP task');
 const review={...task,state:'review',revision:3,updatedAt:3,currentDeliveryId:'delivery',deliveries:[{id:'delivery',number:1,submittedAt:3,git:deliveryGit}]};
 assert.deepEqual(taskView(review,{includeGit:true}).deliveries[0].git,deliveryGit);
 assert.equal(taskResult('getTask',{ok:true,task:review}).task.deliveries[0].git,undefined);
 assert.equal(taskView({...review,deliveries:[{id:'delivery',number:1,submittedAt:3}]}),null,'Git delivery metadata cannot disappear silently');
 const command={conversationId:'chat',taskId:'task',action:'submit',expectedRevision:2,deliveryId:'delivery',clientCommandId:'submit'};
 assert.equal(taskCommand({...command,deliveryGit}),null,'renderer cannot submit Git descriptors');
 const handlers=new Map();
 const service={ok:true,getTask:value=>tasks.get(value),changeTask:value=>tasks.submit(value)};
 createCollaborationIpc({ipcMain:{handle:(name,handler)=>handlers.set(name,handler)},getService:()=>service});
 assert.equal((await handlers.get('collaboration:get-task')({}, {conversationId:'chat',taskId:'task'})).task.inputGit,undefined,'actual IPC handler strips internal descriptor');
 assert.equal((await handlers.get('collaboration:change-task')({}, {...command,deliveryGit})).ok,false);
 assert.equal((await tasks.submit(command)).ok,false,'Git tasks cannot silently downgrade to ZIP');
 assert.equal(calls.length,0);
 assert.equal((await tasks.submit(command,deliveryGit)).state,'confirming');
 assert.deepEqual(calls[0].deliveryGit,deliveryGit);
 store.close();tasks=open();unknown=false;
 assert.equal((await tasks.retry({clientCommandId:'submit'})).state,'completed');
 assert.deepEqual(calls[1],calls[0],'encrypted restart journal replays identical descriptor');
 assert.equal((await tasks.submit(command,{...deliveryGit,sha256:'0'.repeat(64)})).code,'IDEMPOTENCY_KEY_REUSED');
 console.log('Git desktop: private metadata, closed IPC, no downgrade and immutable encrypted command replay passed');
} finally {store?.close();fs.rmSync(directory,{recursive:true,force:true});}
