import assert from 'node:assert/strict';
import {once} from 'node:events';
import {createRequire} from 'node:module';
import {registerCollaborationRealtimeGateway} from '../server/src/services/collaboration/realtime-gateway.js';
const require=createRequire(new URL('../server/package.json',import.meta.url));
const app=require('fastify')(); const {WebSocket}=require('ws');
let calls=0;
const unavailable=async()=>{calls++;throw Error('unavailable');};
registerCollaborationRealtimeGateway(app,{ticketService:{consume:async()=>({userId:'u',deviceId:'d'})},presence:{connect:unavailable,touch:unavailable,disconnect:unavailable,clear:unavailable,expiredIds:()=>[]}});
const base=await app.listen({host:'127.0.0.1',port:0});
const ws=new WebSocket(base.replace('http:','ws:')+'/api/collaboration/v1/realtime?ticket=test');
await once(ws,'open');
const ack=new Promise(resolve=>ws.on('message',raw=>{if(JSON.parse(raw).type==='realtime.heartbeat-ack')resolve();}));
ws.send(JSON.stringify({type:'realtime.heartbeat',schemaVersion:1}));await ack;
assert.ok(calls>=2,'async presence failures do not interrupt heartbeat');
let closed=false;const closing=app.close().then(()=>{closed=true;});
await Promise.race([closing,new Promise(resolve=>setTimeout(resolve,500))]);
const closedInTime=closed;
ws.terminate();await closing;
assert.equal(closedInTime,true,'shutdown cleans active upgraded sockets without waiting for peer disconnect');
console.log('Presence gateway: async rejection isolation and active-socket shutdown passed');
