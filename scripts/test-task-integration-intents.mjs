import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {createRequire} from 'node:module';
import {execFile} from 'node:child_process';
import {promisify} from 'node:util';
const require=createRequire(import.meta.url);
const {CollaborationStore}=require('../src/main/collaboration/collaboration-store');
const {LocalCollaborationKeyring}=require('../src/main/collaboration/local-keyring');
const {createIntegrationIntents}=require('../src/main/collaboration/integration-intents');
const root=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'integration-intents-'));
const keyring=new LocalCollaborationKeyring({filePath:path.join(root,'keys'),safeStorage:{isEncryptionAvailable:()=>true,encryptString:s=>Buffer.from(s),decryptString:b=>b.toString()}});
let now=1000,stopped=false;
const stores=[];
const open=()=>{
  const store=new CollaborationStore({dbPath:path.join(root,'db'),accountId:'owner',keyring});stores.push(store);
  return {store,intents:createIntegrationIntents({store,now:()=>now,assertActive(){if(stopped)throw new Error('stopped');}})};
};
const input={conversationId:'chat',workspaceId:'shared',taskId:'task',deliveryId:'delivery',targetId:'project-root',chain:'shared',sessionId:'session',projectId:'project',baselineCommit:'a'.repeat(40),deliveryCommit:'b'.repeat(40)};
try {
  const a=open();a.store.replaceProjectionFromBootstrap({conversations:[{id:'chat',scopeId:'team:org',kind:'channel'},{id:'other',scopeId:'team:org',kind:'channel'}]});
  const first=a.intents.enqueue(input),b=open();
  assert.deepEqual(b.intents.enqueue(input),first,'duplicate event is the same durable intent');
  assert.throws(()=>b.intents.enqueue({...input,deliveryCommit:'c'.repeat(40)}),/CONFLICT/,'same delivery target cannot silently change frozen input');
  const local=b.intents.enqueue({...input,chain:'local'});assert.notEqual(local.id,first.id);
  const cross=b.intents.enqueue({...input,conversationId:'other',workspaceId:'another',deliveryId:'second'});
  const lease=a.intents.claim(first.id,{workerId:'one',leaseMs:100});assert.equal(lease.generation,1);
  assert.equal(b.intents.claim(local.id,{workerId:'two',leaseMs:100}),null,'shared and local writes to the same target serialize');
  assert.equal(b.intents.claim(cross.id,{workerId:'two',leaseMs:100}),null,'target identity fences different workspace/conversation mappings too');
  assert.throws(()=>b.intents.assertLease({...lease,workerId:'two'}),/FENCED/);
  now=1100;assert.throws(()=>a.intents.complete(lease),/FENCED/,'expiry fences completion even before a successor claims');
  const successor=b.intents.claim(first.id,{workerId:'two',leaseMs:100});assert.equal(successor.generation,2);
  for(const method of ['assertLease','renew','release','complete'])assert.throws(()=>a.intents[method](lease),/FENCED/,'stale worker cannot mutate replacement ownership');
  now=1150;const renewed=b.intents.renew(successor,100);assert.equal(renewed.expiresAt,1250);
  a.intents.assertLease(renewed);b.intents.release(renewed);
  assert.equal(a.intents.get(first.id).state,'pending');
  const retry=a.intents.claim(first.id,{workerId:'three',leaseMs:100});assert.equal(retry.generation,3);
  a.intents.complete(retry);assert.equal(b.intents.get(first.id).state,'completed');
  assert.equal(b.intents.claim(first.id,{workerId:'four',leaseMs:100}),null,'completed duplicate cannot run again');
  const localLease=b.intents.claim(local.id,{workerId:'four',leaseMs:100});assert.equal(localLease.generation,4);
  b.intents.cancel(local.id);assert.throws(()=>a.intents.assertLease(localLease),/FENCED/);
  const independent=a.intents.enqueue({...input,deliveryId:'third',targetId:'another-root'});
  assert.ok(a.intents.claim(independent.id,{workerId:'parallel',leaseMs:100}),'independent target does not inherit a workspace-wide global lock');
  const row=a.store.db.get('SELECT * FROM task_workspace_records WHERE id=?',first.id);
  assert.doesNotMatch(row.payload_envelope_json,/project-root|baselineCommit|session/,'intent metadata stays encrypted');
  const lockRows=a.store.db.all('SELECT * FROM task_integration_leases');
  assert.doesNotMatch(JSON.stringify(lockRows),/project-root|another-root/,'plaintext lease keys are opaque target hashes');
  const race=a.intents.enqueue({...input,deliveryId:'race',targetId:'race-root'});
  const child=`const {CollaborationStore}=require(${JSON.stringify(require.resolve('../src/main/collaboration/collaboration-store'))});
    const {LocalCollaborationKeyring}=require(${JSON.stringify(require.resolve('../src/main/collaboration/local-keyring'))});
    const {createIntegrationIntents}=require(${JSON.stringify(require.resolve('../src/main/collaboration/integration-intents'))});
    const keyring=new LocalCollaborationKeyring({filePath:${JSON.stringify(path.join(root,'keys'))},safeStorage:{isEncryptionAvailable:()=>true,encryptString:s=>Buffer.from(s),decryptString:b=>b.toString()}});
    const store=new CollaborationStore({dbPath:${JSON.stringify(path.join(root,'db'))},accountId:'owner',keyring});
    try {const intents=createIntegrationIntents({store,now:()=>2000,assertActive(){}});console.log(JSON.stringify(intents.claim(${JSON.stringify(race.id)},{workerId:String(process.pid),leaseMs:1000})));}
    catch(error){if(error.errcode===5||error.errcode===517)console.log('"busy"');else throw error;}finally{store.close();}`;
  const results=await Promise.all([1,2].map(()=>promisify(execFile)(process.execPath,['-e',child],{timeout:15000})));
  const claims=results.map(result=>JSON.parse(result.stdout));
  assert.equal(claims.filter(result=>result && result!=='busy').length,1,'separate processes grant exactly one target writer');
  stopped=true;assert.throws(()=>b.intents.enqueue(input),/stopped/);stopped=false;
  a.store.revokeScope({scopeId:'team:org'});
  assert.throws(()=>b.intents.assertLease(renewed),/MISSING|REVOKED|FENCED/,'scope retirement cannot leave an executable intent');
  assert.equal(a.store.db.get('SELECT count(*) n FROM task_workspace_records').n,0);
  console.log('integration intents: two SQLite connections and competing processes, immutable event dedupe, target serialization, expiry/generation fencing, renewal/retry/completion/cancel and revoked scope passed');
}finally{for(const store of stores)store.close();fs.rmSync(root,{recursive:true,force:true});}
