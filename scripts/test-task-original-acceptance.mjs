import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createTaskRun, buildTaskToolEvidence, addTaskEvidence } = require('../src/main/task-run-state');
const { createTaskRunRuntime } = require('../src/main/task-run-runtime');
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'lily-original-acceptance-'));
try {
  const state = { turnId: 'original', taskContract: { active: true, taskType: 'code_change' }, taskCore: { contract: { acceptanceCriteria: ['focused_test', 'build'], requestedDeliverables: [] } }, taskRun: createTaskRun({ turnId: 'original' }) };
  state.taskRun.successCriteria = ['focused_test'];
  addTaskEvidence(state.taskRun, buildTaskToolEvidence({ id: 'test', name: 'bash', status: 'done', completionObserved: true, input: { command: 'npm test' }, metadata: { exit: 0 } }));
  createTaskRunRuntime({ getState: () => state }).complete('s', 'turn.completed');
  assert.equal(state.taskRun.verification.status, 'unverified', 'original build criterion must survive a reduced current checklist');
  const { inspectDeliverables } = require('../src/main/task-delivery-manifest');
  let manifest = inspectDeliverables([{ path: 'result.json' }, { path: 'REPORT.md' }, 'modified_code'], root);
  assert.equal(manifest.filter(x => x.status === 'missing').length, 2);
  assert.equal(manifest.length, 2, 'logical labels are not filenames');
  fs.writeFileSync(path.join(root, 'result.json'), '{}');
  fs.writeFileSync(path.join(root, 'REPORT.md'), '');
  manifest = inspectDeliverables(['result.json', 'REPORT.md'], root);
  assert.deepEqual(manifest.map(x => x.status), ['exists', 'empty']);
  assert.equal(inspectDeliverables([{ path: '../outside.md' }], root)[0].repairable, false);
  assert.equal(inspectDeliverables([{ path: 'relative.json' }], '')[0].status, 'unresolved');
  fs.symlinkSync(os.tmpdir(), path.join(root, 'escape'), process.platform === 'win32' ? 'junction' : 'dir');
  assert.equal(inspectDeliverables([{ path: 'escape/absent.json' }], root)[0].repairable, false, 'symlink escape cannot authorize repair');
  const { detectIncompleteDeliverable } = require('../src/main/opencode-todo-completion-policy');
  assert.equal(detectIncompleteDeliverable('Done', { deliverables: [{ path: 'missing.json' }], workspacePath: root })?.path, path.join(fs.realpathSync(root), 'missing.json'), 'engine correction uses the structured contract, not just final prose');
  assert.equal(detectIncompleteDeliverable(`Generated ${root}/absent.md`)?.path, `${root}/absent.md`);
  const { buildIntentContractToolDefinition } = require('../src/main/mcp/intent-contract-tool-definition');
  const definition = buildIntentContractToolDefinition();
  const input = [{ path: 'reports/Quarterly  Report.md' }, { path: 'LICENSE' }];
  assert.equal(definition.inputSchema.deliverables.safeParse(input).success, true, 'real model entry accepts typed output identity');
  const candidate = await definition.handler({ objective: 'Write report', deliverables: input });
  const { normalizeIntentContract } = require('../src/main/intent-contract');
  const normalized = normalizeIntentContract(candidate.intentContract);
  const { createTaskCoreEnvelope } = require('../src/main/task-core-contracts');
  const core = createTaskCoreEnvelope({ sessionId: 's', admission: { sessionId: 's', turnId: 't' }, contextSnapshot: { sessionId: 's' }, taskContract: { active: true, taskType: 'code_change', intentContract: normalized } });
  assert.deepEqual(core.contract.requestedDeliverables, input, 'immutable contract preserves spaces and extensionless typed filenames');
  assert.equal(inspectDeliverables(core.contract.requestedDeliverables, root).filter(x => x.status === 'missing').length, 2);
  console.log('task original acceptance passed');
} finally { fs.rmSync(root, { recursive: true, force: true }); }
