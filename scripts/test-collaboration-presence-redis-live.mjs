import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { randomUUID, createHash } from 'node:crypto';
import { createRedisPresence, createPresenceRedisLifecycle } from '../server/src/services/collaboration/presence-redis.js';
import { registerCollaborationRealtimeGateway } from '../server/src/services/collaboration/realtime-gateway.js';
import { once } from 'node:events';
const connectionFile = process.env.PRESENCE_TEST_CONNECTION_FILE;
if (!connectionFile) { console.log('SKIP Redis integration: PRESENCE_TEST_CONNECTION_FILE not set'); process.exit(0); }
const {url} = JSON.parse(await readFile(connectionFile,'utf8'));
const require = createRequire(new URL('../server/package.json', import.meta.url));
const {createClient} = require('redis');
const namespace = `lily-test:${randomUUID()}`;
const a = createClient({url,disableOfflineQueue:true});
const b = createClient({url,disableOfflineQueue:true});
a.on('error',()=>{}); b.on('error',()=>{});
await Promise.all([a.connect(),b.connect()]);
const one = createRedisPresence({client:a,namespace});
const two = createRedisPresence({client:b,namespace});
const entries=[{userId:'u',activeDevices:new Set(['d1','d2']),activeSessions:new Map([['s1','d1'],['s2','d2']])},{userId:'v',activeDevices:new Set(['d3']),activeSessions:new Map([['s3','d3']])}];
let lifecycle;
let app;
let socket;
try {
 await one.connect('old',{userId:'u',deviceId:'d1',sessionId:'s1'});
 await two.connect('new',{userId:'u',deviceId:'d1',sessionId:'s1'});
 await one.disconnect('old');
 assert.equal((await one.readBatch(entries))[0].presence,'online','old disconnect cannot remove new instance lease');
 await one.connect('other',{userId:'u',deviceId:'d2',sessionId:'s2'});
 await two.disconnect('new');
 assert.equal((await two.readBatch(entries))[0].presence,'online','multi-device aggregation is global');
 assert.equal((await two.readBatch(entries))[1].presence,'unknown','empty Redis starts in recovery warmup, not false offline');
 await a.set(`${namespace}:presence-epoch`,'1');
 await one.connect('session-old',{userId:'v',deviceId:'d3',sessionId:'revoked-session'});
 assert.equal((await two.readBatch([{userId:'v',activeDevices:new Set(['d3']),activeSessions:new Map([['other-active-session','d3']])}]))[0].presence,'offline','another active session on the same device cannot validate the socket session');
 await one.disconnect('session-old');
 await one.connect('legacy',{userId:'v',deviceId:'d3'});
 assert.equal((await two.readBatch(entries))[1].presence,'offline','legacy unbound transport does not claim online');
 await one.disconnect('legacy');
 assert.equal((await two.readBatch([{userId:'u',activeDevices:new Set(['d1']),activeSessions:new Map([['s1','d1']])}]))[0].presence,'offline','revoked device excluded');
 const userKey=`${namespace}:presence:${createHash('sha256').update('u').digest('hex')}`;
 await a.zAdd(userKey,{score:1,value:JSON.stringify(['d2','other','s2'])});
 assert.equal((await two.readBatch(entries))[0].presence,'offline','Redis server time expires crashed connection');
 await one.touch('other');
 assert.equal((await two.readBatch(entries))[0].presence,'online','heartbeat recreates expired lease');
 await one.disconnect('other');
 const connecting=one.connect('raced',{userId:'u',deviceId:'d1',sessionId:'s1'});
 const touching=one.touch('raced');
 const disconnecting=one.disconnect('raced');
 await Promise.all([connecting,touching,disconnecting]);
 assert.equal((await two.readBatch(entries))[0].presence,'offline','queued renewals before close cannot resurrect closed connection');
 const results=await Promise.all(Array.from({length:31},(_,i)=>(i%2?one:two).allowQuery('query-user')));
 assert.equal(results.filter(Boolean).length,30,'rate limit shared by instances');
 let hints=0;
 let gateway;
 lifecycle=await createPresenceRedisLifecycle({url,namespace,onHint:()=>{hints++;gateway?.notifyPresenceChanged();}});
 assert.deepEqual(lifecycle.health(),{configured:true,ready:true,subscriberReady:true});
 await a.publish(lifecycle.store.channel,'changed');
 await new Promise(resolve=>setTimeout(resolve,100));
 assert.ok(hints>0,'PubSub crosses independent clients');
 await a.publish(lifecycle.store.channel,JSON.stringify({userId:'private'}));
 const previous=hints;
 await new Promise(resolve=>setTimeout(resolve,30));
 assert.equal(hints,previous,'unexpected payload ignored');
 // Exercise the receiving gateway using independent Redis publishers, not just
 // a producer-local counter. No user identity appears in the delivered hint.
 app=require('fastify')();
 gateway=registerCollaborationRealtimeGateway(app,{ticketService:{consume:async()=>({userId:'viewer',deviceId:'viewer-device',sessionId:'viewer-session'})}});
 const base=await app.listen({host:'127.0.0.1',port:0});
 const {WebSocket}=require('ws');
 socket=new WebSocket(base.replace('http:','ws:')+'/api/collaboration/v1/realtime?ticket=fixture');
 await once(socket,'open');
 const received=[];socket.on('message',raw=>{const frame=JSON.parse(raw);if(frame.type==='presence.changed')received.push(frame);});
 await Promise.all(Array.from({length:100},(_,i)=>(i%2?a:b).publish(lifecycle.store.channel,'changed')));
 await new Promise(resolve=>setTimeout(resolve,1100));
 assert.equal(received.length,1,'independent publishing instances share one bounded gateway fanout');
 await b.publish(lifecycle.store.channel,'changed');await a.publish(lifecycle.store.channel,'changed');
 await new Promise(resolve=>setTimeout(resolve,1100));
 assert.equal(received.length,2,'trailing final cross-instance change is not lost');
 assert.deepEqual(received[1],{type:'presence.changed',schemaVersion:1},'hint has no identity payload');
 console.log('Real Redis: cross-instance aggregation, old disconnect, revoked device, expiry, recovery, shared limit and PubSub passed');
} finally { socket?.terminate(); await app?.close(); await one.clear(); await two.clear(); await lifecycle?.stop(); const keys=await a.keys(`${namespace}:*`); if(keys.length)await a.del(keys); a.destroy();b.destroy(); }
