import assert from 'node:assert/strict';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { indexDesc, shortIndexDesc, buildSkillIndexSection, createIndexReport } = require('../src/main/agent-guide-index');
assert.equal(typeof indexDesc,'function','negative routing descriptions supported');
const {parseFrontmatter} = require('../src/main/skill-md-convert');
const real = parseFrontmatter(fs.readFileSync('resources/skills/lily-image-generation/SKILL.md','utf8')).meta.description;
assert.ok(indexDesc(real).includes('NOT for structural content'));
assert.ok(indexDesc(real).includes('lily-diagrams'));
const noise = `${'普通触发说明'.repeat(40)}。禁止路由字段只是字段说明。不要把账号密码写进聊天。`;
assert.equal(indexDesc(noise),shortIndexDesc(noise),'nonrouting prohibitions not appended');
assert.equal(indexDesc('short'), 'short');
assert.ok(indexDesc(real).length <= 343,'bounded expansion');
process.env.LILY_GUIDE_INDEX_NEGATIVE='0';
assert.equal(indexDesc(real),shortIndexDesc(real),'kill switch returns exact baseline');
const entryOf = s => ({id:s.id,desc:s.desc});
const skills=[{id:'one',desc:real},{id:'two',desc:'second skill must remain discoverable'}];
const baseline = buildSkillIndexSection(skills,'en',Infinity,null,entryOf);
delete process.env.LILY_GUIDE_INDEX_NEGATIVE;
const report=createIndexReport();
const result=buildSkillIndexSection(skills,'en',Buffer.byteLength(baseline),report,entryOf);
assert.deepEqual(report.indexedIds,['one','two'],'negative tails cannot evict baseline skills');
assert.ok(Buffer.byteLength(result)<=Buffer.byteLength(baseline));
assert.ok(buildSkillIndexSection(skills,'en',Infinity,null,entryOf).includes('NOT for structural content'));
console.log('skill-index-negative-routing: ok');
