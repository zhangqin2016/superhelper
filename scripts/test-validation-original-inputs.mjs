import assert from 'node:assert/strict';
import fs from 'node:fs';import os from 'node:os';import path from 'node:path';import {createHash} from 'node:crypto';import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {TaskGit}=require('../src/main/collaboration/task-git');
const {createSharedGit}=require('../src/main/collaboration/shared-git');
const {createValidationOriginalInputs}=require('../src/main/collaboration/validation-original-inputs');
const root=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'validation-original-'));
const hash=value=>createHash('sha256').update(value).digest('hex');
const snapshot=(name,files)=>{const dir=path.join(root,name);fs.mkdirSync(dir);return {snapshotRoot:dir,manifest:Object.entries(files).map(([name,text])=>{fs.writeFileSync(path.join(dir,name),text);return {path:name,sizeBytes:Buffer.byteLength(text),sha256:hash(text)};})};};
try{
 const taskGit=new TaskGit({rootPath:path.join(root,'git'),gitOptions:{autoInstall:false}}),shared=createSharedGit(taskGit);
 const base=snapshot('base',{'original-test.json':'{"expected":2}','value.json':'{"value":2}','oversize.txt':'x'.repeat(4*1024*1024+1)});
 const baseline=await taskGit.captureBaseline({taskId:'task',...base});
 const changed=snapshot('changed',{'value.json':'{"value":0}'});
 const delivery=await taskGit.captureContribution({baseline,baseManifest:base.manifest,materializedPaths:base.manifest.map(f=>f.path),deliveryId:'delivery',...changed});
 const head=await shared.initialize({workspaceId:'workspace',baseline});
 const headFiles=snapshot('head',{'original-test.json':'{"expected":2}','value.json':'{"value":2}','head-check.json':'{"newCheck":true}'});
 const headDelivery=await taskGit.captureContribution({baseline,baseManifest:base.manifest,materializedPaths:base.manifest.map(f=>f.path),deliveryId:'head-delivery',...headFiles});
 const first=await shared.prepare({workspaceId:'workspace',baseline,delivery:headDelivery,expectedHead:head.commit});
 await shared.publish({candidate:first,validate:async c=>({ok:true,commit:c.commit})});
 const candidate=await shared.prepare({workspaceId:'workspace',baseline,delivery,expectedHead:first.commit});
 const inputs=createValidationOriginalInputs({taskGit,candidate,temporaryRoot:root,assertActive(){}});
 const original=await inputs.read({version:'baseline',path:'original-test.json'});
 assert.equal(original.commit,baseline.commit);assert.deepEqual(JSON.parse(original.bytes),{expected:2});
 original.bytes.fill(0);
 assert.deepEqual(JSON.parse((await inputs.read({version:'head',path:'original-test.json'})).bytes),{expected:2},'caller buffers cannot alter immutable originals');
 assert.equal((await inputs.read({version:'delivery',path:'original-test.json'})).state,'absent','deletion is distinguishable from unreadable data');
 assert.equal((await inputs.read({version:'baseline',path:'head-check.json'})).state,'absent');
 const headCheck=await inputs.read({version:'head',path:'head-check.json'});
 assert.equal(headCheck.commit,first.commit);assert.deepEqual(JSON.parse(headCheck.bytes),{newCheck:true},'checks added to published H remain separately available');
 await assert.rejects(inputs.read({version:'private',path:'original-test.json'}),/INVALID/);
 await assert.rejects(inputs.read({version:'baseline',path:'../outside'}),/INVALID/);
 const evidence=inputs.close();assert.equal(evidence.reads.length,5);assert.equal(evidence.reads[2].state,'absent');
 assert.equal(evidence.reads[0].sha256,base.manifest[0].sha256);
 await assert.rejects(inputs.read({version:'baseline',path:'value.json'}),/CLOSED/);
 const fenced=createValidationOriginalInputs({taskGit,candidate,temporaryRoot:root,assertActive(){throw Error('fenced');}});
 await assert.rejects(fenced.read({version:'baseline',path:'value.json'}),/fenced/);
 const unfinished=createValidationOriginalInputs({taskGit,candidate,temporaryRoot:root,assertActive(){}});
 const pending=unfinished.read({version:'baseline',path:'value.json'});
 assert.equal(unfinished.close().pending,1,'a returned host callback cannot conceal outstanding original input work');
 await assert.rejects(pending,/CLOSED/);
 const oversized=createValidationOriginalInputs({taskGit,candidate,temporaryRoot:root,assertActive(){}});
 await assert.rejects(oversized.read({version:'baseline',path:'oversize.txt'}),/LIMIT/);
 assert.equal(oversized.close().totalBytes,0,'oversized original blobs are refused before materialization');
 const limited=createValidationOriginalInputs({taskGit,candidate,temporaryRoot:root,assertActive(){}});
 for(let i=0;i<100;i++)await limited.read({version:'baseline',path:'absent.json'});
 await assert.rejects(limited.read({version:'baseline',path:'absent.json'}),/LIMIT/);
 assert.equal(limited.close().failures,1);
 assert.equal(fs.readdirSync(root).some(name=>name.startsWith('original-input-')),false);
 console.log('original validation inputs: exact B/H/D, removed checks retained, owned bytes, absence provenance, identity/path refusal, close and fencing passed');
}finally{fs.rmSync(root,{recursive:true,force:true});}
