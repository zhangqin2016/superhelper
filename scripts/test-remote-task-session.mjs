import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const require=createRequire(import.meta.url);
const {createRemoteTaskSession,focusRegisteredSession,resolveRemoteTaskBinding,registerRemoteTaskWorkspace}=require('../src/main/collaboration/task-session');
let saved;
const manager={sessions:{},saveImmediate(){saved=JSON.parse(JSON.stringify(this.sessions));}};
const first=createRemoteTaskSession(manager,'project','Remote work','task:helper');
assert.equal(first.status,'idle');assert.deepEqual(first.messages,[]);
assert.equal(saved.project[0].remoteTaskBinding,'task:helper');
manager.sessions=saved;
assert.equal(createRemoteTaskSession(manager,'project','Renamed','task:helper').id,first.id);
assert.notEqual(createRemoteTaskSession(manager,'project','Delivery','task:delivery').id,first.id);
assert.equal(manager.activeSessionId,undefined,'explicit renderer switch owns navigation');
const focusEvents=[];
const focusManager={_find:id=>id===first.id?first:null};
const win={isDestroyed:()=>false,isMinimized:()=>false,show:()=>focusEvents.push('show'),focus:()=>focusEvents.push('focus'),webContents:{send:(...args)=>focusEvents.push(args)}};
assert.equal(focusRegisteredSession(focusManager,win,'unknown').ok,false);
assert.deepEqual(focusEvents,[]);
assert.equal(focusRegisteredSession(focusManager,win,first.id).ok,true);
assert.deepEqual(focusEvents.at(-1),['assistant:focus-session',{sessionId:first.id,projectId:'project'}]);
const temporary=fs.mkdtempSync(path.join(os.tmpdir(),'remote-task-session-'));
const electronPath=require.resolve('electron');
require.cache[electronPath]={id:electronPath,filename:electronPath,loaded:true,exports:{app:{getPath:name=>name==='userData'?path.join(temporary,'userData'):temporary}}};
const SessionManager=require('../src/main/session-manager');
const pm={projects:[{id:'p1',name:'Workspace',path:temporary}],getActive(){return this.projects[0];}};
let live,reopened;
try {
  live=new SessionManager(pm);live.load();
  const active=live.activeSessionId;
  const task=createRemoteTaskSession(live,'p1','Review budget','task:helper');
  const projectManager={find:id=>id==='p1'?pm.projects[0]:null};
  task.status='running';const beforeBinding=JSON.stringify(task);
  const bound=resolveRemoteTaskBinding(projectManager,live,{projectId:'p1',sessionId:task.id,bindingId:'shared',title:'Shared work'});
  assert.equal(JSON.stringify(task),beforeBinding,'binding a running session cannot alter its engine/session state');
  assert.deepEqual(bound,{projectId:'p1',sessionId:task.id,rootPath:fs.realpathSync(temporary)});
  assert.throws(()=>resolveRemoteTaskBinding(projectManager,live,{projectId:'p1',sessionId:'missing',bindingId:'shared'}),{code:'COLLAB_TASK_LOCAL_MISSING'});
  assert.throws(()=>resolveRemoteTaskBinding(projectManager,live,{projectId:'deleted',sessionId:task.id,bindingId:'shared'}),{code:'COLLAB_TASK_LOCAL_MISSING'});
  const foreign={find:id=>({id,path:temporary})};
  assert.throws(()=>resolveRemoteTaskBinding(foreign,live,{projectId:'other',sessionId:task.id,bindingId:'shared'}),{code:'COLLAB_TASK_LOCAL_MISSING'});
  const generated=resolveRemoteTaskBinding(projectManager,live,{projectId:'p1',bindingId:'shared',title:'Shared work'});
  const executionRoot=fs.realpathSync(fs.mkdtempSync(path.join(temporary,'execution-')));
  const execution=registerRemoteTaskWorkspace(projectManager,live,{projectId:'p1',rootPath:executionRoot,bindingId:'task-execution',title:'Work'});
  assert.equal(execution.projectId,'p1');
  assert.equal(live._find(execution.sessionId).remoteTaskExecution.rootPath,executionRoot);
  assert.equal(resolveRemoteTaskBinding(projectManager,live,{projectId:'p1',bindingId:'shared'}).sessionId,generated.sessionId,'multiple tasks reuse one workspace session');
  assert.equal(live.activeSessionId,active,'registration does not steal the active conversation');
  live.close();live=null;
  reopened=new SessionManager(pm);reopened.load();
  assert.equal(registerRemoteTaskWorkspace(projectManager,reopened,{projectId:'p1',rootPath:executionRoot,bindingId:'task-execution'}).sessionId,execution.sessionId);
  assert.equal(resolveRemoteTaskBinding(projectManager,reopened,{projectId:'p1',bindingId:'shared'}).sessionId,generated.sessionId,'real persisted session index preserves shared binding');
  assert.equal(createRemoteTaskSession(reopened,'p1','Review budget','task:helper').id,task.id,'real disk index preserves idempotent task binding');
  assert.deepEqual(reopened.getConversation(task.id),[],'opening the task must not enqueue a prompt or start an engine');
} finally {live?.close();reopened?.close();fs.rmSync(temporary,{recursive:true,force:true});}
console.log('remote task session passed');
