import assert from 'node:assert/strict';
import { createOnlinePresence, ONLINE_TTL_MS } from '../server/src/services/collaboration/online-presence.js';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createEnterpriseDirectoryReader } = require('../src/main/collaboration/enterprise-directory');
let time = 100000;
const tracker = createOnlinePresence({ now: () => time });
tracker.connect('one', { userId: 'u', deviceId: 'd1' });
tracker.connect('two', { userId: 'u', deviceId: 'd2' });
const devices = new Set(['d1', 'd2']);
assert.ok(tracker.expiresAt('u', devices));
tracker.disconnect('one'); assert.ok(tracker.expiresAt('u', devices), 'second active device keeps user online');
assert.equal(tracker.expiresAt('u', new Set(['d1'])), null, 'revoked device cannot count');
time += ONLINE_TTL_MS + 1; assert.equal(tracker.expiresAt('u', devices), null);
tracker.touch('two'); assert.ok(tracker.expiresAt('u', devices));
tracker.disconnect('two'); assert.equal(tracker.expiresAt('u', devices), null);
const local = { profile: { userId: 'u' }, contacts: [], teams: [{ id: 'org', members: [{ userId: 'u' }] }] };
let fail = false;
const reader = createEnterpriseDirectoryReader({ now: () => time, client: { getEnterpriseDirectory: async () => { if(fail) throw new Error('network'); return { profile: local.profile, teams: [] }; } } });
assert.equal((await reader(local)).teams.length, 0, 'live removal replaces old members');
fail = true; time += 11000;
assert.equal((await reader(local)).teams.length, 0, 'network failure must not resurrect removed membership');
const offline = createEnterpriseDirectoryReader({ client: { getEnterpriseDirectory: async () => { throw new Error('network'); } } });
assert.equal((await offline(local)).teams[0].members[0].presence, 'unknown', 'offline cache is not proof of online');
console.log('enterprise presence: expiry, multi-device, revocation and offline fallback passed');
