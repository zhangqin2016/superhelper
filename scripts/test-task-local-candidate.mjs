import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const {prepareLocalCandidate}=require('../src/main/collaboration/task-local-candidate');
const {createTaskApplication}=require('../src/main/collaboration/task-application');
const {createLocalWriter}=require('../src/main/collaboration/local-writer');
const dir=fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()),'lily-local-candidate-'));
const paths=Object.fromEntries(['a','w','m','stage','journal'].map(key=>{const p=path.join(dir,key);fs.mkdirSync(p);return [key,p];}));
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const manifest=files=>Object.entries(files).map(([name,bytes])=>({path:name,sizeBytes:Buffer.byteLength(bytes),sha256:hash(bytes)}));
const save=(root,files)=>{for(const [name,bytes]of Object.entries(files))fs.writeFileSync(path.join(root,name),bytes);};
const a={'doc.txt':'one\ntwo\nthree\nfour\nfive\n','kept.txt':'shared old','remove.txt':'remove','local-delete.txt':'base','config.json':'{"a":1,"b":2}\n'};
const w={...a,'doc.txt':'PRIVATE\ntwo\nthree\nfour\nfive\n','kept.txt':'private note','unrelated.txt':'secret','config.json':'{"a":3,"b":2}\n'};delete w['local-delete.txt'];
const m={...a,'doc.txt':'one\ntwo\nthree\nfour\nremote\n','new.txt':'remote add','config.json':'{"a":1,"b":4}\n'};delete m['remove.txt'];
const input={base:{rootPath:paths.a,manifest:manifest(a)},shared:{rootPath:paths.m,manifest:manifest(m)},rootPath:paths.w,destinationRoot:paths.stage,assertActive(){}};
try {
  save(paths.a,a);save(paths.w,w);save(paths.m,m);
  const candidate=await prepareLocalCandidate(input);
  assert.equal(candidate.state,'ready');
  assert.equal(fs.readFileSync(path.join(candidate.snapshotRoot,'doc.txt'),'utf8'),'PRIVATE\ntwo\nthree\nfour\nremote\n');
  assert.equal(fs.readFileSync(path.join(candidate.snapshotRoot,'kept.txt'),'utf8'),'private note');
  assert.deepEqual(JSON.parse(fs.readFileSync(path.join(candidate.snapshotRoot,'config.json'))),{a:3,b:4});
  assert.equal(fs.existsSync(path.join(candidate.snapshotRoot,'local-delete.txt')),false,'unchanged shared file must not resurrect a private deletion');
  assert.equal(candidate.manifest.some(file=>file.path==='unrelated.txt'),false,'untracked private file stays outside managed materialization inventory');
  assert.equal(fs.readFileSync(path.join(paths.w,'doc.txt'),'utf8'),w['doc.txt'],'preparation never mutates W');
  const records=new Map(),writer=createLocalWriter({filePath:path.join(dir,'writer.sqlite')});
  const broker=createTaskApplication({journalRoot:paths.journal,writer,assertAuthorized:async()=>true,journal:{get:id=>records.get(id),put:(id,value)=>records.set(id,structuredClone(value))}});
  const apply={applicationId:'local',rootPath:paths.w,deliveryRoot:candidate.snapshotRoot,baseManifest:candidate.currentManifest,deliveryManifest:candidate.manifest,editablePaths:candidate.paths};
  const preview=await broker.preview(apply);
  fs.writeFileSync(path.join(paths.w,'doc.txt'),'later edit');
  await assert.rejects(broker.apply({...apply,expectedPlanHash:preview.planHash,confirmDeletions:true}),/PREVIEW_CHANGED/);
  save(paths.w,{'doc.txt':w['doc.txt']});
  await broker.apply({...apply,expectedPlanHash:preview.planHash,confirmDeletions:true});
  assert.equal(fs.readFileSync(path.join(paths.w,'unrelated.txt'),'utf8'),'secret');
  assert.equal(fs.existsSync(path.join(paths.w,'remove.txt')),false);
  assert.equal((await broker.recover({applicationId:'local',mode:'rollback'})).state,'rolled_back');
  assert.equal(fs.readFileSync(path.join(paths.w,'doc.txt'),'utf8'),w['doc.txt'],'rollback restores W, not shared A');
  save(paths.w,{'doc.txt':'conflicting\n','remove.txt':'private deletion conflict'});
  const conflict=await prepareLocalCandidate(input);
  assert.equal(conflict.state,'conflicts');
  assert.ok(conflict.conflicts.some(file=>file.path==='doc.txt'));
  assert.ok(conflict.conflicts.some(file=>file.path==='remove.txt'));
  assert.equal(fs.readFileSync(path.join(paths.w,'remove.txt'),'utf8'),'private deletion conflict');
  fs.writeFileSync(path.join(paths.w,'new.txt'),'private collision');
  const collision=await prepareLocalCandidate(input);
  assert.ok(collision.conflicts.some(file=>file.path==='new.txt'&&file.reason==='add_add'));
  fs.unlinkSync(path.join(paths.w,'new.txt'));
  for(const [key,bytes]of [['a',Buffer.from([0,1])],['w',Buffer.from([0,2])],['m',Buffer.from([0,3])]])save(paths[key],{'binary.docx':bytes});
  const binary=await prepareLocalCandidate({...input,base:{...input.base,manifest:[...input.base.manifest,...manifest({'binary.docx':Buffer.from([0,1])})]},shared:{...input.shared,manifest:[...input.shared.manifest,...manifest({'binary.docx':Buffer.from([0,3])})]}});
  assert.ok(binary.conflicts.some(file=>file.path==='binary.docx'));
  assert.deepEqual(fs.readFileSync(path.join(paths.w,'binary.docx')),Buffer.from([0,2]),'binary conflict never round-trips or overwrites private bytes');
  fs.writeFileSync(path.join(paths.m,'new.txt'),'corrupt');
  await assert.rejects(prepareLocalCandidate(input),/SNAPSHOT_CHANGED/);
  save(paths.m,{'new.txt':'remote add'});
  fs.symlinkSync(paths.w,path.join(dir,'alias'));
  await assert.rejects(prepareLocalCandidate({...input,rootPath:path.join(dir,'alias')}),/UNSAFE_PATH/);
  await assert.rejects(prepareLocalCandidate({...input,destinationRoot:paths.w}),/ROOT_OVERLAP/);
  let checks=0;
  await assert.rejects(prepareLocalCandidate({...input,assertActive(){if(++checks>1)throw Error('revoked');}}),/revoked/);
  checks=0;
  save(paths.w,{'doc.txt':w['doc.txt']});
  await assert.rejects(prepareLocalCandidate({...input,assertActive(){if(++checks===3)fs.writeFileSync(path.join(paths.w,'doc.txt'),'changed during merge');}}),/INPUT_CHANGED/);
  console.log('local A/W/M candidate: real text/JSON merge, private edits/deletions, conflicts, stale apply, rollback and guards passed');
} finally {fs.rmSync(dir,{recursive:true,force:true});}
