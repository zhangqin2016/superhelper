import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { DatabaseRecoveryService } = require('../src/main/database-recovery-service');
const children = [];
const forkImpl = () => {
  const child = new EventEmitter();
  child.send = message => { child.request = message; };
  child.kill = signal => { child.killed = signal; };
  children.push(child);
  return child;
};
const service = new DatabaseRecoveryService('/temporary/messages.db', { forkImpl, timeoutMs: 25 });
const first = service.run('inspect');
assert.equal((await service.run('inspect')).reason, 'busy');
const child = children[0];
child.emit('message', { type: 'database-recovery-result', result: { ok: true } });
assert.equal((await service.run('prepare')).reason, 'busy', 'receipt cannot release a still-live writer');
child.emit('exit', 0, null);
assert.equal((await first).ok, true);
assert.equal((await service.run('arbitrary')).reason, 'invalid_action');
assert.equal(children.length, 1);
const timed = service.run('inspect');
await new Promise(resolve => setTimeout(resolve, 40));
assert.equal(children[1].killed, 'SIGKILL');
assert.equal((await service.run('inspect')).reason, 'busy', 'timeout cannot overlap a worker before its exit');
children[1].emit('exit', null, 'SIGKILL');
assert.equal((await timed).reason, 'timeout');
const interrupted = service.run('restore', 'candidate');
children[2].emit('message', { type: 'database-recovery-result', result: { ok: true } });
children[2].emit('exit', 1, null);
assert.equal((await interrupted).reason, 'worker_exit', 'abnormal exit cannot claim confirmed restoration');
const cancelled = service.run('backup');
service.close();
children[3].emit('exit', null, 'SIGKILL');
assert.equal((await cancelled).reason, 'cancelled');
assert.equal((await service.run('inspect')).reason, 'closed');
console.log('PASS recovery worker bounds, exit fencing, invalid actions, cancellation');
