import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import crypto from 'node:crypto';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { createTaskApplication } = require('../src/main/collaboration/task-application');
const dir = fs.mkdtempSync(path.join(fs.realpathSync(os.tmpdir()), 'lily-application-'));
const rootPath = path.join(dir, 'root'), deliveryRoot = path.join(dir, 'delivery'), journalRoot = path.join(dir, 'journal');
for (const p of [rootPath, deliveryRoot, journalRoot]) fs.mkdirSync(p);
const manifest = (name, bytes) => ({ path:name, sizeBytes:Buffer.byteLength(bytes), sha256:crypto.createHash('sha256').update(bytes).digest('hex') });
const records = new Map();
const journal = { get:id=>structuredClone(records.get(id)), put:(id,value)=>records.set(id,structuredClone(value)) };
const broker = createTaskApplication({ journal, journalRoot, assertAuthorized: async()=>true });
const baseManifest = [manifest('edit.txt','old'),manifest('delete.txt','gone')];
const deliveryManifest = [manifest('edit.txt','new'),manifest('nested/add.txt','added')];
fs.writeFileSync(path.join(rootPath,'edit.txt'),'old'); fs.writeFileSync(path.join(rootPath,'delete.txt'),'gone'); fs.writeFileSync(path.join(rootPath,'unrelated.txt'),'keep');
fs.writeFileSync(path.join(deliveryRoot,'edit.txt'),'new'); fs.mkdirSync(path.join(deliveryRoot,'nested')); fs.writeFileSync(path.join(deliveryRoot,'nested/add.txt'),'added');
const input = { applicationId:'app-1',rootPath,deliveryRoot,baseManifest,deliveryManifest,editablePaths:['edit.txt','delete.txt','nested/add.txt'] };
try {
  const preview = await broker.preview(input);
  await assert.rejects(broker.apply({...input, expectedPlanHash:preview.planHash}), /DELETION_CONFIRMATION/);
  fs.writeFileSync(path.join(rootPath,'edit.txt'),'local');
  await assert.rejects(broker.apply({...input, expectedPlanHash:preview.planHash,confirmDeletions:true}), /PREVIEW_CHANGED/);
  assert.equal((await broker.preview(input)).plan.entries.find(e=>e.path==='edit.txt').status,'conflict');
  fs.writeFileSync(path.join(rootPath,'edit.txt'),'old');
  fs.writeFileSync(path.join(deliveryRoot,'edit.txt'),'tampered');
  await assert.rejects(broker.preview(input), /DELIVERY_MISMATCH/);
  fs.writeFileSync(path.join(deliveryRoot,'edit.txt'),'new');
  fs.symlinkSync(deliveryRoot,path.join(rootPath,'nested'));
  await assert.rejects(broker.preview(input), /UNSAFE_PATH/);
  fs.unlinkSync(path.join(rootPath,'nested'));
  const result = await broker.apply({...input,expectedPlanHash:preview.planHash,confirmDeletions:true});
  assert.equal(result.state,'applied');
  assert.equal(fs.readFileSync(path.join(rootPath,'edit.txt'),'utf8'),'new');
  assert.equal(fs.existsSync(path.join(rootPath,'delete.txt')),false);
  assert.equal(fs.readFileSync(path.join(rootPath,'nested/add.txt'),'utf8'),'added');
  assert.equal(fs.readFileSync(path.join(rootPath,'unrelated.txt'),'utf8'),'keep');
  assert.deepEqual(await broker.apply({...input,expectedPlanHash:preview.planHash,confirmDeletions:true}), result);
  fs.writeFileSync(path.join(rootPath,'edit.txt'),'later edit');
  const recovery = await broker.recover({applicationId:input.applicationId,mode:'rollback'});
  assert.equal(recovery.state,'recovery_conflict');
  assert.equal(fs.readFileSync(path.join(rootPath,'edit.txt'),'utf8'),'later edit');
  fs.writeFileSync(path.join(rootPath,'edit.txt'),'new');
  assert.equal((await broker.recover({applicationId:input.applicationId,mode:'rollback'})).state,'rolled_back');
  assert.equal(fs.readFileSync(path.join(rootPath,'edit.txt'),'utf8'),'old');
  assert.equal(fs.readFileSync(path.join(rootPath,'delete.txt'),'utf8'),'gone');
  // Fail after the filesystem write but before its completion journal checkpoint.
  const brokenJournal = {get:journal.get,put(id,value){ if(value.operations?.some(o=>o.state==='done')) throw new Error('injected journal failure'); journal.put(id,value); }};
  const broken = createTaskApplication({journal:brokenJournal,journalRoot,assertAuthorized:async()=>true});
  const second = {...input,applicationId:'app-2'};
  const next = await broken.preview(second);
  await assert.rejects(broken.apply({...second,expectedPlanHash:next.planHash,confirmDeletions:true}),/injected/);
  assert.equal((await broker.recover({applicationId:'app-2',mode:'rollback'})).state,'rolled_back');
  assert.equal(fs.readFileSync(path.join(rootPath,'edit.txt'),'utf8'),'old');
  const third = {...input,applicationId:'app-3'};
  const thirdPreview = await broker.preview(third);
  const rename = fs.renameSync;
  try {
    fs.renameSync = () => { throw new Error('injected write failure'); };
    await assert.rejects(broker.apply({...third,expectedPlanHash:thirdPreview.planHash,confirmDeletions:true}),/injected write failure/);
  } finally { fs.renameSync = rename; }
  assert.equal((await broker.recover({applicationId:'app-3',mode:'rollback'})).state,'rolled_back');
  assert.equal(fs.readdirSync(rootPath).some(name=>name.startsWith('.lily-apply-')),false);
  const denied = createTaskApplication({journal,journalRoot,assertAuthorized:async()=>false});
  await assert.rejects(denied.preview(input),/FORBIDDEN/);
  const outside = {...input,applicationId:'app-4',editablePaths:[]};
  const outsidePreview = await broker.preview(outside);
  await assert.rejects(broker.apply({...outside,expectedPlanHash:outsidePreview.planHash,confirmDeletions:true}),/CONFLICT/);
  // Another program edits a target at the write checkpoint: no stale overwrite.
  const racingJournal = {get:journal.get,put(id,value){ journal.put(id,value); if(value.operations?.some(o=>o.state==='writing')) fs.writeFileSync(path.join(rootPath,'edit.txt'),'raced'); }};
  const racing = createTaskApplication({journal:racingJournal,journalRoot,assertAuthorized:async()=>true});
  const fourth = {...input,applicationId:'app-5'};
  const fourthPreview = await racing.preview(fourth);
  await assert.rejects(racing.apply({...fourth,expectedPlanHash:fourthPreview.planHash,confirmDeletions:true}),/INPUT_CHANGED/);
  assert.equal(fs.readFileSync(path.join(rootPath,'edit.txt'),'utf8'),'raced');
  assert.equal((await broker.recover({applicationId:'app-5',mode:'rollback'})).state,'recovery_conflict');
  fs.writeFileSync(path.join(rootPath,'edit.txt'),'old');
  fs.renameSync(path.join(rootPath,'edit.txt'),path.join(rootPath,'EDIT.TXT'));
  await assert.rejects(broker.preview({...input,applicationId:'case'}),/UNSAFE_PATH/);
  fs.renameSync(path.join(rootPath,'EDIT.TXT'),path.join(rootPath,'edit.txt'));
  const fifth = {...input,applicationId:'app-6'};
  const fifthPreview = await broker.preview(fifth);
  await broker.apply({...fifth,expectedPlanHash:fifthPreview.planHash,confirmDeletions:true});
  const saved = journal.get('app-6');
  const editOperation = saved.operations.find(operation=>operation.path==='edit.txt');
  fs.writeFileSync(path.join(saved.backupDirectory,editOperation.backupName),'corrupt backup');
  await assert.rejects(broker.recover({applicationId:'app-6',mode:'rollback'}),/BACKUP_MISMATCH/);
  assert.equal(fs.readFileSync(path.join(rootPath,'edit.txt'),'utf8'),'new');
  console.log('remote task application: preview, conflicts, integrity, symlinks, deletion, idempotency and crash rollback passed');
} finally { fs.rmSync(dir,{recursive:true,force:true}); }
