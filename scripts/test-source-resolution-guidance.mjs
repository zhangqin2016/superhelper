import assert from "node:assert/strict";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const { sourceResolutionGuidance } = require("../src/main/source-resolution-guidance");
const { buildTaskContract, withTaskContractPrefix } = require("../src/main/task-contract");
const { extractUserOriginalRequest } = require("../src/main/engine-message-layers");
const request = "把附件里的表格转成清晰的要点列表";
const contract = buildTaskContract({ text: request, files: [] });
const prompt = withTaskContractPrefix(request, contract);
assert.match(prompt, /Source resolution precedes/);
assert.doesNotMatch(prompt, /expected_output: artifact|page_coverage|output_opens/);
assert.equal(extractUserOriginalRequest(prompt), request);
assert.match(prompt, /authorizes normal inspection and processing/);
assert.equal(sourceResolutionGuidance({ ...contract, priorSourceContentEvidence: true }), "");
assert.equal(sourceResolutionGuidance({ ...contract, contentIntent: { ...contract.contentIntent, attachmentKinds: ["spreadsheet"] } }), "");
assert.equal(sourceResolutionGuidance({ ...contract, contentIntent: { ...contract.contentIntent, operation: "create" } }), "");
assert.equal(sourceResolutionGuidance({ ...contract, intentContract: { relation: "continue" } }), "");
assert.equal(sourceResolutionGuidance({}), "");
assert.equal(sourceResolutionGuidance({ ...contract, externalFactPolicy: { required: true } }), "");
console.log("source resolution: inferred deliverables deferred, actual-source and creation paths retained");
