import assert from 'node:assert/strict';
import fs from 'node:fs';
const composePath = new URL('../deploy/baota/docker-compose.redis.yml', import.meta.url);
assert.ok(fs.existsSync(composePath), 'Redis deployment must be explicitly configured');
const compose = fs.readFileSync(composePath, 'utf8');
const entry = fs.readFileSync(new URL('../deploy/baota/redis-entrypoint.sh', import.meta.url), 'utf8');
assert.match(compose, /127\.0\.0\.1:16379:6379/, 'Redis never binds a public host port');
assert.match(compose, /redis_password/, 'Authentication comes from a secret file');
assert.doesNotMatch(compose, /--requirepass|REDIS_PASSWORD:/, 'No password in process args or compose environment');
assert.match(entry, /requirepass/, 'Redis requires authentication');
assert.match(entry, /maxmemory-policy noeviction/, 'Capacity exhaustion cannot silently evict live leases');
assert.match(entry, /save ""/, 'Ephemeral status is not a durability dependency');
assert.match(entry, /appendonly no/);
assert.match(entry, /chmod 600/);
assert.match(compose, /redis-healthcheck\.sh/);
const apiOverridePath = new URL('../deploy/baota/docker-compose.presence-api.yml', import.meta.url);
assert.ok(fs.existsSync(apiOverridePath), 'API rollout must not change the shared website image tag');
const apiOverride = fs.readFileSync(apiOverridePath, 'utf8');
assert.match(apiOverride, /COLLABORATION_API_IMAGE/);
assert.doesNotMatch(apiOverride, /\n  web:|lily-workbench-web/);
console.log('Redis deploy: loopback, secret file, authenticated health, bounded ephemeral memory.');
